"""Phase 3 figures and markdown tables from results/tables/phase3_*.csv (no model fitting).

Run from `05 Code`:  python scripts/phase3_report.py
"""
import ast
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.loaders import RESULTS_DIR  # noqa: E402

TAB, FIG = RESULTS_DIR / "tables", RESULTS_DIR / "figures"
INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e4e3df"
STYLE = {"logreg": ("#2a78d6", "o", "logistic regression"), "rf": ("#eb6834", "s", "random forest"),
         "gb": ("#1baf7a", "^", "gradient boosting"), "stump": ("#8a8984", "D", "single-feature threshold"),
         "majority": ("#b5b4ae", "x", "majority class")}
CONDS = [("within-class chunks", "all rows"), ("within-class chunks", "clean rows"),
         ("random rows (optimistic reference)", "all rows"), ("random rows (optimistic reference)", "clean rows")]
COND_LABEL = ["chunks\nall rows", "chunks\nclean rows", "random rows\nall rows", "random rows\nclean rows"]
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                     "figure.facecolor": "#fcfcfb", "axes.facecolor": "#fcfcfb",
                     "axes.edgecolor": MUTED, "xtick.color": MUTED, "ytick.color": MUTED})


def pm(m, s):
    return "n/a" if pd.isna(m) else f"{m:.3f} ± {0 if pd.isna(s) else s:.3f}"


def md(df):
    cols = list(df.columns)
    out = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    for _, r in df.iterrows():
        out += "| " + " | ".join(f"{v:.3f}" if isinstance(v, float) else str(v) for v in r) + " |\n"
    return out


if __name__ == "__main__":
    s = pd.read_csv(TAB / "phase3_summary.csv")

    # ---- figure: 2 tasks x 2 feature sets, dot plot over the 4 validation conditions
    panels = [("4_class", "bal_acc", "4 classes: balanced accuracy"),
              ("waste_vs_rest", "roc_auc", "waste vs rest: ROC-AUC")]
    fig, axes = plt.subplots(2, 2, figsize=(11, 6.5), sharex=True)
    x = np.arange(len(CONDS))
    offs = dict(zip(STYLE, np.linspace(-0.24, 0.24, len(STYLE))))
    for i, (task, metric, title) in enumerate(panels):
        for j, fs in enumerate(["all_13", "basic_6"]):
            ax = axes[i, j]
            sub = s[(s.task == task) & (s.features == fs)]
            for m, (col, mk, lab) in STYLE.items():
                vals = [sub[(sub.scheme == sc) & (sub.subset == su) & (sub.model == m)][f"{metric}_mean"].iloc[0]
                        for sc, su in CONDS]
                ax.plot(x + offs[m], vals, ls="none", marker=mk, ms=7, color=col, label=lab)
            ax.axvspan(1.5, 3.5, color=GRID, alpha=0.5, lw=0)
            ax.text(2.5, 0.27, "optimistic reference only", ha="center", fontsize=7, color=MUTED)
            ax.set_ylim(0.25, 1.02)
            ax.grid(axis="y", color=GRID)
            ax.set_title(f"{title} — {'all 13 features' if fs == 'all_13' else '6 basic features (no pressure/force/torque)'}",
                         fontsize=8.5, color=INK)
            ax.set_xticks(x, COND_LABEL, fontsize=7.5)
    axes[0, 0].legend(fontsize=7, frameon=False, loc="lower left")
    fig.suptitle("Polenta lenses: results by validation scheme and row subset (mean over 5 seeds)", fontsize=10)
    fig.tight_layout()
    fig.savefig(FIG / "phase3_polenta_overview.png", dpi=150)
    plt.close(fig)

    # ---- confusion matrix figure: RF, all 13, chunks, all rows vs clean rows (seed 0, row-normalised)
    cm = pd.read_csv(TAB / "phase3_confusion.csv")
    names = ["waste", "acceptable", "target", "inefficient"]
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.8))
    for ax, subset in zip(axes, ["all rows", "clean rows"]):
        r = cm[(cm.task == "4_class") & (cm.features == "all_13") & (cm.subset == subset)
               & (cm.scheme == "within-class chunks") & (cm.model == "rf") & (cm.seed == 0)].iloc[0]
        m = np.array(ast.literal_eval(r.cm), float)
        mn = m / m.sum(axis=1, keepdims=True)
        ax.imshow(mn, cmap="Blues", vmin=0, vmax=1)
        for a in range(4):
            for b in range(4):
                ax.text(b, a, f"{mn[a, b]:.2f}\n({int(m[a, b])})", ha="center", va="center", fontsize=7.5,
                        color="white" if mn[a, b] > 0.6 else INK)
        ax.set_xticks(range(4), names, fontsize=7.5)
        ax.set_yticks(range(4), names, fontsize=7.5)
        ax.set_xlabel("predicted")
        ax.set_ylabel("true")
        ax.set_title(f"random forest, all 13, chunks — {subset}", fontsize=8.5)
    fig.tight_layout()
    fig.savefig(FIG / "phase3_polenta_confusion.png", dpi=150)
    plt.close(fig)

    # ---- markdown tables
    lines = ["# Phase 3 tables (generated by scripts/phase3_report.py)\n"]
    for task, cols in [("4_class", ["accuracy", "bal_acc", "roc_auc"]),
                       ("waste_vs_rest", ["accuracy", "bal_acc", "bal_acc_05", "roc_auc", "pr_auc",
                                          "false_alarm_rate_acceptable"])]:
        sub = s[s.task == task].copy()
        out = sub[["features", "subset", "scheme", "model"]].copy()
        for c in cols:
            out[c] = [pm(a, b) for a, b in zip(sub[f"{c}_mean"], sub.get(f"{c}_std_seeds", np.nan))] \
                if f"{c}_std_seeds" in sub else sub[f"{c}_mean"].round(3)
        out["min balanced acc. over folds"] = sub["fold_bacc_min_mean"].round(3)
        out["majority rate"] = sub["majority_rate"].round(3)
        lines.append(f"\n## {task}\n")
        lines.append(md(out))
    (TAB / "phase3_tables.md").write_text("\n".join(lines), encoding="utf-8")
    print("written", TAB / "phase3_tables.md")
