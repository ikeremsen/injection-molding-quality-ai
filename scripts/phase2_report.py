def ladder_plot(summ, target, metric, ylabel, fname, ylim=(0.3, 1.02), ref=0.5):
    fig, axes = plt.subplots(1, 4, figsize=(13, 3.6), sharey=True)
    x = np.arange(len(LADDER))
    for ax, (scheme, test, title) in zip(axes, PANELS):
        sub = summ[(summ.target == target) & (summ.scheme == scheme) & (summ.test == test)]
        npos = sub["n_pos_groups"].iloc[0] if len(sub) else 0
        ax.set_title(f"{title}\nNOK groups in test: {npos}" if target else title, fontsize=8.5, color=INK)
        ax.axhline(ref, color=MUTED, lw=1, ls=":")
        ax.text(len(LADDER) - 0.6, ref + 0.01, "chance", color=MUTED, fontsize=7, ha="right", va="bottom")
        ax.grid(axis="y", color=GRID, lw=0.8)
        if sub[f"{metric}_mean"].isna().all():
            ax.text(2, (ylim[0] + ylim[1]) / 2, "not computable\n(only one class in test)",
                    ha="center", color=MUTED, fontsize=8)
        for m, st in STYLE.items():
            s = sub[sub.model == m].set_index("features").reindex(LADDER)
            ax.errorbar(x, s[f"{metric}_mean"], yerr=s[f"{metric}_std"], color=st["color"],
                        marker=st["marker"], ms=5, lw=2, ls=st.get("ls", "-"), capsize=2,
                        label=st["label"])
        ax.set_xticks(x, LADDER_LABEL, fontsize=6.5, rotation=0)
        ax.set_ylim(*ylim)
    axes[0].set_ylabel(ylabel)
    axes[0].legend(loc="lower left", fontsize=7, frameon=False)
    fig.suptitle(f"{target}: {ylabel} along the feature ladder (mean ± std over seeds)", fontsize=10, color=INK)
    fig.tight_layout()
    fig.savefig(FIG / fname, dpi=150)
    plt.close(fig)


def md_table(df, cols, floatfmt=".2f"):
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    body = ""
    for _, r in df[cols].iterrows():
        body += "| " + " | ".join(f"{v:{floatfmt}}" if isinstance(v, float) else str(v) for v in r) + " |\n"
    return head + body


def pm(m, s):
    return "n/a" if pd.isna(m) else f"{m:.2f} ± {0 if pd.isna(s) else s:.2f}"


