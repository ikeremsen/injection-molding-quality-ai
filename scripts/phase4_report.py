"""Phase 4 figures and tables (no model fitting).

Run from `05 Code` after phase4_skz.py and phase4_polenta.py:
    python scripts/phase4_report.py
"""
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.loaders import RESULTS_DIR  # noqa: E402
from src.signals import CHANNEL_INFO  # noqa: E402

TAB, FIG = RESULTS_DIR / "tables", RESULTS_DIR / "figures"
INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e4e3df"
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                     "figure.facecolor": "#fcfcfb", "axes.facecolor": "#fcfcfb",
                     "axes.edgecolor": MUTED, "xtick.color": MUTED, "ytick.color": MUTED})
CH_ORDER = list(CHANNEL_INFO)
SKZ_T = ["LBL_NOK", "LBL_SinkMarks", "LBL_Underfilled", "SCA_PartWeight"]
COLS_LABEL = {"LBL_NOK": "SKZ\nNOK", "LBL_SinkMarks": "SKZ\nsink marks", "LBL_Underfilled": "SKZ\nunderfilled",
              "SCA_PartWeight": "SKZ\npart weight", "waste_vs_rest": "Polenta\nwaste", "4_class": "Polenta\n4 classes"}


def md(df):
    cols = list(df.columns)
    s = "| " + " | ".join(map(str, cols)) + " |\n|" + "---|" * len(cols) + "\n"
    for _, r in df.iterrows():
        s += "| " + " | ".join(f"{v:.3f}" if isinstance(v, float) else str(v) for v in r) + " |\n"
    return s


if __name__ == "__main__":
    sk_imp = pd.read_csv(TAB / "phase4_skz_importance.csv")
    sk_shap = pd.read_csv(TAB / "phase4_skz_shap_features.csv")
    sk_steps = pd.read_csv(TAB / "phase4_skz_selection_steps.csv")
    sk_scores = pd.read_csv(TAB / "phase4_skz_selection_scores.csv")
    po_imp = pd.read_csv(TAB / "phase4_polenta_importance.csv")
    po_shap = pd.read_csv(TAB / "phase4_polenta_shap.csv")
    po_steps = pd.read_csv(TAB / "phase4_polenta_selection_steps.csv")
    po_scores = pd.read_csv(TAB / "phase4_polenta_selection_scores.csv")

    lines = ["# Phase 4 tables (generated by scripts/phase4_report.py)\n"]

    # ---------- A. selection frequency: share of outer folds x seeds in which a channel is among the first 3 picks
    def top3_share(steps, key, keyval, extra=None):
        s = steps[(steps[key] == keyval) & (steps.k <= 3)]
        if extra is not None:
            s = s[extra(s)]
        n_runs = s.groupby(["seed", "fold"]).ngroups
        return s.groupby("added").size().reindex(CH_ORDER).fillna(0) / n_runs

    freq = pd.DataFrame({
        **{t: top3_share(sk_steps, "target", t, lambda s: s.variant == "measured signals only") for t in SKZ_T},
        **{t: top3_share(po_steps, "task", t, lambda s: s.subset == "clean rows") for t in ["waste_vs_rest", "4_class"]},
    })
    first = pd.DataFrame({
        **{t: sk_steps[(sk_steps.target == t) & (sk_steps.variant == "measured signals only") & (sk_steps.k == 1)]
           .added.value_counts(normalize=True).reindex(CH_ORDER).fillna(0) for t in SKZ_T},
        **{t: po_steps[(po_steps.task == t) & (po_steps.subset == "clean rows") & (po_steps.k == 1)]
           .added.value_counts(normalize=True).reindex(CH_ORDER).fillna(0) for t in ["waste_vs_rest", "4_class"]},
    })
    ch_rows = [c for c in CH_ORDER if c != "setpoints"]
    fig, ax = plt.subplots(figsize=(8.2, 5.2))
    M = freq.loc[ch_rows].values
    ax.imshow(np.where(np.isnan(M), 0, M), cmap="Blues", vmin=0, vmax=1, aspect="auto")
    polenta_has = {"screw_position", "melt_pressure", "plastification", "clamp_force", "phase_timing",
                   "barrel_temperature", "mold_temperature"}
    for i, ch in enumerate(ch_rows):
        for j, t in enumerate(freq.columns):
            if t in ("waste_vs_rest", "4_class") and ch not in polenta_has:
                ax.text(j, i, "not\nlogged", ha="center", va="center", fontsize=6.5, color=MUTED)
                continue
            v = freq.loc[ch, t]
            ax.text(j, i, f"{v:.0%}", ha="center", va="center", fontsize=8, color="white" if v > 0.6 else INK)
    ax.set_xticks(range(len(freq.columns)), [COLS_LABEL[c] for c in freq.columns], fontsize=8)
    ax.set_yticks(range(len(ch_rows)), [c.replace("_", " ") for c in ch_rows])
    ax.axvline(3.5, color="white", lw=4)
    ax.set_title("How often a signal is among the first 3 picked (nested forward selection,\n"
                 "measured signals only; SKZ 15 runs, Polenta clean rows 15 runs)", fontsize=9.5)
    fig.tight_layout()
    fig.savefig(FIG / "phase4_signal_selection_heatmap.png", dpi=150)
    plt.close(fig)
    lines.append("\n## Share of runs in which a channel is among the first 3 picks (measured signals only)\n")
    lines.append(md(freq.loc[ch_rows].reset_index().rename(columns={"index": "channel", "added": "channel"})))
    lines.append("\n## Share of runs in which a channel is the FIRST pick\n")
    lines.append(md(first.loc[ch_rows].reset_index().rename(columns={"index": "channel", "added": "channel"})))

    # ---------- B. selection curves: outer score vs number of channels
    fig, axes = plt.subplots(1, 6, figsize=(15, 3.4))
    panels = [("skz", t) for t in SKZ_T] + [("po", t) for t in ["waste_vs_rest", "4_class"]]
    curve_rows = []
    for ax, (src, t) in zip(axes, panels):
        if src == "skz":
            sub = sk_scores[sk_scores.target == t]
            variants = [("with setpoints", "#8a8984", "--"), ("measured signals only", "#2a78d6", "-")]
            vcol = "variant"
        else:
            sub = po_scores[po_scores.task == t]
            variants = [("all rows", "#8a8984", "--"), ("clean rows", "#eb6834", "-")]
            vcol = "subset"
        for v, col, ls in variants:
            s = sub[sub[vcol] == v]
            ks = s[s.k != "all"].copy()
            ks["k"] = ks.k.astype(int)
            g = ks.groupby("k").outer_score.agg(["mean", "std"])
            vals = -g["mean"] if t == "SCA_PartWeight" else g["mean"]
            ax.errorbar(g.index, vals, yerr=g["std"], color=col, ls=ls, marker="o", ms=4, lw=2, capsize=2, label=v)
            allv = s[s.k == "all"].outer_score.mean()
            allv = -allv if t == "SCA_PartWeight" else allv
            ax.axhline(allv, color=col, lw=1, ls=":")
            for k_, m_ in vals.items():
                curve_rows.append(dict(data=src, target=t, variant=v, k=k_, score=m_, all_channels=allv))
        ax.set_title(COLS_LABEL[t].replace("\n", " "), fontsize=9)
        ax.set_xlabel("number of channels")
        ax.set_xticks(range(1, 6))
        ax.grid(axis="y", color=GRID)
        ax.set_ylabel("offset-corrected MAE [g] (lower is better)" if t == "SCA_PartWeight" else "ROC-AUC")
        ax.legend(fontsize=6.5, frameon=False, loc="lower right" if t != "SCA_PartWeight" else "upper right")
    fig.suptitle("Outer-fold score when the logger records only the k best channels "
                 "(dotted = all channels)", fontsize=10)
    fig.tight_layout()
    fig.savefig(FIG / "phase4_selection_curves.png", dpi=150)
    plt.close(fig)
    lines.append("\n## Outer score vs number of channels (mean over seeds)\n")
    lines.append(md(pd.DataFrame(curve_rows)))

    # ---------- C. channel permutation + SHAP shares
    perm = (sk_imp.groupby(["target", "model", "channel"]).perm_drop.mean().unstack(["target", "model"]))
    lines.append("\n## SKZ channel permutation importance (score drop, within-day shuffles; weight in grams of MAE)\n")
    lines.append(md(perm.reindex(CH_ORDER).reset_index()))
    sh = sk_shap.groupby(["target", "model", "channel"]).mean_abs_shap.sum().groupby(level=[0, 1]).transform(
        lambda s: s / s.sum()).unstack(["target", "model"])
    lines.append("\n## SKZ SHAP share per channel (sum of mean |SHAP| of its features / total)\n")
    lines.append(md(sh.reindex(CH_ORDER).reset_index()))
    pp = po_imp[po_imp.level == "channel"].groupby(["task", "subset", "name"]).perm_drop.mean().unstack(["task", "subset"])
    lines.append("\n## Polenta channel permutation importance (AUC drop)\n")
    lines.append(md(pp.reset_index()))
    pf = po_imp[po_imp.level == "feature"].groupby(["task", "subset", "name"]).perm_drop.mean().unstack(["task", "subset"])
    lines.append("\n## Polenta feature permutation importance (AUC drop)\n")
    lines.append(md(pf.reset_index()))

    # ---------- D. top SHAP features (SKZ NOK logreg, SKZ weight rf, Polenta waste clean)
    fig, axes = plt.subplots(1, 3, figsize=(14, 4.6))
    specs = [(sk_shap[(sk_shap.target == "LBL_NOK") & (sk_shap.model == "logreg")], "SKZ NOK — logistic regression"),
             (sk_shap[(sk_shap.target == "SCA_PartWeight") & (sk_shap.model == "rf")], "SKZ part weight — random forest"),
             (po_shap[(po_shap.task == "waste_vs_rest") & (po_shap.subset == "clean rows")], "Polenta waste — RF, clean rows")]
    for ax, (d, title) in zip(axes, specs):
        top = d.groupby(["feature", "channel"]).mean_abs_shap.mean().sort_values().tail(12).reset_index()
        ax.barh(range(len(top)), top.mean_abs_shap, color="#2a78d6", height=0.7)
        ax.set_yticks(range(len(top)), [f"{f[:38]}  [{c.replace('_', ' ')}]" for f, c in zip(top.feature, top.channel)],
                      fontsize=6.8)
        ax.set_title(title, fontsize=9)
        ax.set_xlabel("mean |SHAP| on test folds")
        ax.grid(axis="x", color=GRID)
    fig.tight_layout()
    fig.savefig(FIG / "phase4_top_shap_features.png", dpi=150)
    plt.close(fig)
    for d, title in specs:
        top = d.groupby(["feature", "channel"]).mean_abs_shap.mean().sort_values(ascending=False).head(15).reset_index()
        lines.append(f"\n## Top SHAP features: {title}\n")
        lines.append(md(top))
    (TAB / "phase4_tables.md").write_text("\n".join(lines), encoding="utf-8")
    print("written", TAB / "phase4_tables.md")
